num1 = 48
num2 = 86

print("Number 1", num1)
print("Number 2", num2)

#Addition
print("Addition:", num1 + num2)

#Subtraction
print("Subtraction:", num1 - num2)

#Multiplication
print("Multiplication:", num1 * num2)

#Division  
print("Division:", num1 / num2)

#Comparison operators
#equality
print(num1 == num2)
print(num1 != num2)
print(num1 > num2)
print(num1 < num2)
print(num1 >= num2)
print(num1 <= num2)

#Expression
result = (num1/2) + (num2 * 3) - 10
print(result)